"""Pinned source and distributable provisioning assets; no guest/tool execution."""
import hashlib
import json
import os
from pathlib import Path
import shutil
import stat
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[1]
LOCK = "Config/DevVMProvisioning.lock.json"
BUNDLE = "DevVMProvisioning_DevVMProvisioningCore.bundle"
EXECUTABLES = ("OmarchyVMProvisioningHelper", "dev-vm-process-host")


def require(condition, message="Invalid provisioning package"):
    if not condition:
        raise ValueError(message)


def sha(data):
    return hashlib.sha256(data).hexdigest()


def files(root, maximum=512, total_limit=8*1024*1024):
    require(root.is_dir() and not root.is_symlink())
    result, total = {}, 0
    pending = [(root, "")]
    while pending:
        directory, prefix = pending.pop()
        for entry in directory.iterdir():
            name = prefix + entry.name
            info = entry.lstat()
            require(not info.st_mode & 0o022, "Writable provisioning entry")
            if stat.S_ISDIR(info.st_mode):
                require(name.count("/") < 32)
                pending.append((entry, name + "/"))
            else:
                require(stat.S_ISREG(info.st_mode), "Linked/special provisioning entry")
                total += info.st_size
                require(len(result) < maximum and total <= total_limit)
                result[name] = sha(entry.read_bytes())
    return result


def read_lock(root=ROOT):
    raw = (root / LOCK).read_bytes()
    require(len(raw) <= 65536)
    value = json.loads(raw)
    require(value["format"] == 1 and value["setupAPI"] == 1 and value["package"] == "Vendor/dev-vm")
    require(value["resourceBundle"] == BUNDLE and value["launcher"] == EXECUTABLES[1])
    return raw, value


def resource_files(lock):
    prefix = "Sources/DevVMProvisioningCore/Resources/"
    return {name[len(prefix):]: value for name, value in lock["files"].items() if name.startswith(prefix)}


def pin_source(raw, lock):
    entries = ",\n".join("        " + json.dumps(k) + ": " + json.dumps(v) for k,v in sorted(resource_files(lock).items()))
    return ("// Generated by make prepare-source; immutable reviewed package pin.\n"
            "public enum ProvisioningPackagePin {\n"
            f'    public static let revision = "{lock["revision"]}"\n'
            f'    public static let lockSHA256 = "{sha(raw)}"\n'
            f'    public static let engineSHA256 = "{lock["engineSHA256"]}"\n'
            f'    public static let sourceSnapshotSHA256 = "{lock["sourceSnapshotSHA256"]}"\n'
            f'    public static let resourceBundle = "{BUNDLE}"\n'
            "    public static let resources: [String: String] = [\n" + entries + "\n    ]\n}\n")


def verify_source(root=ROOT):
    """Verify the export without generating pins or build inputs."""
    require(not any(os.environ.get(name) == "1" for name in
                    ("TOMLDECODER_BENCHMARKS", "TOMLDECODER_DOCS", "TOMLDECODER_FORMATTING"))
            and "SPI_GENERATE_DOCS" not in os.environ, "Optional parser build plugins are not admitted")
    raw, lock = read_lock(root)
    require(files(root / lock["package"]) == lock["files"], "Pinned dev-vm source changed")
    require(sha(json.dumps(lock["files"], sort_keys=True, separators=(",", ":")).encode()) == lock["sourceSnapshotSHA256"])
    patches = lock.get("integrationPatches", [])
    require(len(patches) <= 8)
    if patches:
        with tempfile.TemporaryDirectory(prefix="provisioning-source-check-") as temporary:
            checkout = Path(temporary) / "source"
            shutil.copytree(root / lock["package"], checkout)
            for patch in reversed(patches):
                require(patch["path"].startswith("Patches/") and ".." not in Path(patch["path"]).parts)
                path = root / patch["path"]
                require(path.is_file() and not path.is_symlink() and sha(path.read_bytes()) == patch["sha256"], "Changed provisioning integration patch")
                result = subprocess.run(["/usr/bin/git", "apply", "--reverse", str(path.resolve())], cwd=checkout, capture_output=True)
                require(result.returncode == 0, "Provisioning integration patch cannot be verified")
            require(files(checkout) == lock["baseFiles"], "Provisioning patch base differs")
    else:
        require(lock["files"] == lock["baseFiles"], "Unpatched provisioning base differs")
    require(lock["engineSHA256"] == lock["files"]["Sources/DevVMProvisioningCore/Resources/engine-identity.json"])
    return raw, lock


def prepare(root=ROOT):
    raw, lock = verify_source(root)
    pin = root / "Sources/OmarchyVMManagerCore/ProvisioningPackagePin.swift"
    require(not pin.is_symlink())
    expected = pin_source(raw, lock)
    if not pin.exists() or pin.read_text() != expected:
        pin.write_text(expected)
    # Build the unchanged pinned C entry point in a tiny standalone SwiftPM
    # package. The dependency's executable product isn't a root build product.
    launcher = root / ".build/provisioning-launcher-source"
    require(not launcher.is_symlink())
    (launcher / "Sources").mkdir(parents=True, exist_ok=True)
    manifest = ('// swift-tools-version: 6.0\nimport PackageDescription\n'
                'let package = Package(name: "PinnedProvisioningLauncher", platforms: [.macOS(.v15)], '
                'products: [.executable(name: "dev-vm-process-host", targets: ["dev-vm-process-host"])], '
                'targets: [.executableTarget(name: "dev-vm-process-host", path: "Sources")])\n')
    for path, data in [(launcher / "Package.swift", manifest.encode()),
                       (launcher / "Sources/main.c", (root / lock["package"] / "Sources/dev-vm-process-host/main.c").read_bytes())]:
        require(not path.is_symlink())
        if not path.exists() or path.read_bytes() != data:
            path.write_bytes(data)
    require(set(files(launcher)) == {"Package.swift", "Sources/main.c"}, "Unexpected launcher build input")


def swift_flags(root=ROOT):
    return ["--disable-sandbox", "--skip-update", "--cache-path", str(root / ".build/swiftpm-cache"),
            "--config-path", str(root / ".build/swiftpm-configuration"), "--security-path", str(root / ".build/swiftpm-security")]


def resource_directory(bundle):
    candidates = [p for p in (bundle / "Resources", bundle / "Contents/Resources/Resources") if (p / "engine-identity.json").is_file()]
    require(len(candidates) == 1, "Ambiguous/missing provisioning resources")
    return candidates[0]


def stage(binaries, launcher_binaries, contents, root=ROOT):
    raw, lock = read_lock(root)
    resource = binaries / BUNDLE
    require(files(resource_directory(resource)) == resource_files(lock), "Changed provisioning resources")
    require(all(not p.is_symlink() for p in resource.rglob("*")))
    shutil.copytree(resource, contents / "Resources" / BUNDLE)
    shutil.copy2(root / LOCK, contents / "Resources/DevVMProvisioning.lock.json")
    shutil.copy2(binaries / EXECUTABLES[0], contents / "MacOS" / EXECUTABLES[0])
    shutil.copy2(launcher_binaries / EXECUTABLES[1], contents / "MacOS" / EXECUTABLES[1])


def seal(contents, root=ROOT):
    raw, lock = read_lock(root)
    value = {"format": 1, "lockSHA256": sha(raw), "engineSHA256": lock["engineSHA256"],
             "executables": {n: sha((contents / "MacOS" / n).read_bytes()) for n in EXECUTABLES}}
    (contents / "Resources/ProvisioningDistribution.json").write_text(json.dumps(value, indent=2, sort_keys=True)+"\n")


def verify(contents, root=ROOT):
    raw, lock = read_lock(root)
    require((contents / "Resources/DevVMProvisioning.lock.json").read_bytes() == raw)
    bundle = contents / "Resources" / BUNDLE
    require(all(not p.is_symlink() for p in bundle.rglob("*")))
    require(files(resource_directory(bundle)) == resource_files(lock))
    distribution = json.loads((contents / "Resources/ProvisioningDistribution.json").read_bytes())
    require(distribution == {"format": 1, "lockSHA256": sha(raw), "engineSHA256": lock["engineSHA256"],
            "executables": {n: sha((contents / "MacOS" / n).read_bytes()) for n in EXECUTABLES}})
    for name in EXECUTABLES:
        path = contents / "MacOS" / name
        require(path.is_file() and not path.is_symlink() and os.access(path, os.X_OK))


if __name__ == "__main__":
    prepare()
