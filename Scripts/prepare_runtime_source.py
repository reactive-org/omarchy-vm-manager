#!/usr/bin/env python3
"""Point SwiftPM at the same verified upstream source used to build the kit."""
import hashlib
import json
import re
import os
from pathlib import Path
import uuid
from upstream_source import ROOT, prepare


def update_factory_review_pin(root=ROOT):
    data = (root / 'Sources/OmarchyVMManagerCore/Resources/ReviewedFactories.json').read_bytes()
    values = json.loads(data)
    if len(data) > 65536 or not isinstance(values, list) or len(values) > 1000 or any(not isinstance(value, str) or not re.fullmatch('[0-9a-f]{64}', value) for value in values) or len(set(values)) != len(values):
        raise ValueError('Factory reviews must be a bounded array of unique lowercase SHA-256 digests')
    pin = root / 'Sources/OmarchyVMManagerCore/FactoryReviewPin.swift'
    source = ('// Generated by make prepare-source from the reviewed factory catalog.\n'
              'public enum FactoryReviewPin {\n'
              f'    public static let sha256 = "{hashlib.sha256(data).hexdigest()}"\n'
              '}\n')
    if not pin.exists() or pin.read_text() != source:
        pin.write_text(source)


def main():
    update_factory_review_pin()
    source = prepare()
    link = ROOT / '.build/runtime-source'
    link.parent.mkdir(parents=True, exist_ok=True)
    if link.is_symlink() and link.resolve() == source:
        return
    if link.exists() and not link.is_symlink():
        raise RuntimeError('Unexpected runtime source directory; existing files were preserved')
    temporary = link.with_name('.runtime-source-' + uuid.uuid4().hex)
    try:
        temporary.symlink_to(source, target_is_directory=True)
        os.replace(temporary, link)
    finally:
        temporary.unlink(missing_ok=True)


if __name__ == '__main__':
    main()
